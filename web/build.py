"""Stage the notes and build the site with Zensical.

The notes live at the repo root so that GitHub's own Markdown view stays the
primary reading surface. Zensical wants a *child* directory as `docs_dir`, so we
copy the Markdown tree (preserving paths, hence preserving relative links) into
`web/.build/docs` on every build. Nothing staged is committed: `.gitignore` is
in whitelist mode and only allows what we list there.

Everything web-related lives under `web/`; the only things left outside are
`Makefile` (entry point) and `.github/workflows/site.yml` (GitHub requires it).

Zensical does not support MkDocs `hooks`, so the generated navigation scaffolding
(landing pages per directory + explicit `nav`) is produced here, by
`web/generate.py`, into the staging directory. The effective config is
`web/mkdocs.generated.yml` — `web/mkdocs.yml` plus that nav block.

The same limitation bites the PWA metadata: the theme exposes no head partial to
override (`partials/head.html` is ignored), so `inject_pwa()` appends the
manifest / apple-touch-icon / theme-color / registration tags to every built
page after Zensical runs. `web/sw.js` and `web/manifest.json` must live at the
*site root* — a worker under `/assets/` would only control `/assets/`, and
GitHub Pages cannot send `Service-Worker-Allowed`. `make serve` skips the
injection, so a local preview is a plain site (no install prompt, no offline).

Usage:
    web/build.py            # build web/.build/site
    web/build.py --serve    # live reload on http://127.0.0.1:8000
    web/build.py --strict   # build, fail on warnings (link check)
    web/build.py --stats    # per-area markdown counts (README index)
"""

from __future__ import annotations

import importlib.util
import shutil
import subprocess
import sys
import time
from pathlib import Path

WEB = Path(__file__).resolve().parent
ROOT = WEB.parent
BUILD = WEB / ".build"
DOCS = BUILD / "docs"
CONFIG = WEB / "mkdocs.yml"
GENERATED_CONFIG = WEB / "mkdocs.generated.yml"
STAGED_DIRS = ("assets", "stylesheets")  # inside web/, copied next to the pages
STAGED_FILES = ("LICENSE",)  # README links to it
# Staged into the docs root, not a subdirectory: the service worker's default
# scope is its own directory, and GitHub Pages cannot widen it with headers.
WEB_ROOT_FILES = ("manifest.json", "sw.js")
BUILD_ID_PLACEHOLDER = "__BUILD_ID__"
SKIP_META = {"AGENTS.md", "README.md"}  # README is the GitHub landing page only
SKIP_DIRS = {"web"}  # the site sources themselves are not pages

sys.path.insert(0, str(WEB))
import generate  # noqa: E402 - local module, path set above


def _notes() -> list[Path]:
    found = []
    for path in ROOT.rglob("*.md"):
        rel = path.relative_to(ROOT)
        if any(part.startswith(".") for part in rel.parts):
            continue
        if rel.parts[0] in SKIP_DIRS or rel.name in SKIP_META:
            continue
        found.append(rel)
    return sorted(found)


def stage() -> int:
    if DOCS.exists():
        shutil.rmtree(DOCS)
    DOCS.mkdir(parents=True)
    files = _notes()
    for rel in files:
        dest = DOCS / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, dest)
    for name in STAGED_FILES:
        if (ROOT / name).is_file():
            shutil.copy2(ROOT / name, DOCS / name)
    for name in STAGED_DIRS:
        src = WEB / name
        if src.is_dir():
            shutil.copytree(src, DOCS / name, dirs_exist_ok=True)
    build_id = _build_id()
    for name in WEB_ROOT_FILES:
        src = WEB / name
        if src.is_file():
            text = src.read_text(encoding="utf-8")
            (DOCS / name).write_text(
                text.replace(BUILD_ID_PLACEHOLDER, build_id), encoding="utf-8"
            )
    print(f"staged {len(files)} markdown files -> {DOCS.relative_to(ROOT)}")
    return len(files)


def _build_id() -> str:
    """Short commit sha, so a rebuilt site rotates the service-worker cache."""
    try:
        sha = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        if sha:
            return sha
    except (OSError, subprocess.CalledProcessError):
        pass
    return time.strftime("%Y%m%d%H%M%S")


def write_config() -> Path:
    """Write `web/mkdocs.generated.yml`: the tracked config + generated nav."""
    base = CONFIG.read_text(encoding="utf-8")
    if "\nnav:" in base:
        sys.exit(f"{CONFIG.name} must not define `nav:` — it is generated per build")
    nav = generate.nav_yaml(DOCS)
    GENERATED_CONFIG.write_text(
        "# GENERATED by web/build.py — edit web/mkdocs.yml instead.\n" + base + "\n" + nav,
        encoding="utf-8",
    )
    return GENERATED_CONFIG


def stats() -> None:
    counts: dict[str, int] = {}
    for rel in _notes():
        top = rel.parts[0] if len(rel.parts) > 1 else "(root)"
        counts[top] = counts.get(top, 0) + 1
    total = sum(counts.values())
    for area in sorted(counts):
        print(f"{area:<8} {counts[area]:>3}")
    print(f"{'total':<8} {total:>3}")


FLAGS = {"--serve", "--strict", "-s", "--stats"}

# Prepended to </head> on every page. `{rel}` is the depth-correct prefix, so
# the same block works at the site root and under a deploy subpath.
PWA_HEAD = """<link rel="manifest" href="{rel}manifest.json">
      <link rel="apple-touch-icon" href="{rel}assets/apple-touch-icon.png">
      <meta name="apple-mobile-web-app-capable" content="yes">
      <meta name="mobile-web-app-capable" content="yes">
      <meta name="apple-mobile-web-app-title" content="logbook">
      <meta name="theme-color" content="#a8342a" media="(prefers-color-scheme: light)">
      <meta name="theme-color" content="#12110f" media="(prefers-color-scheme: dark)">
      <script src="{rel}assets/pwa.js" data-sw="{rel}sw.js" defer></script>"""


def inject_pwa() -> int:
    """Add the PWA tags to every built page (see the module docstring).

    Runs on the built site rather than the staged sources because the tags have
    to sit inside <head>, which the theme renders and no partial exposes.
    """
    site = BUILD / "site"
    pages = sorted(site.rglob("*.html"))
    for page in pages:
        rel = page.relative_to(site)
        prefix = "../" * (len(rel.parts) - 1)
        html = page.read_text(encoding="utf-8")
        if 'rel="manifest"' in html:
            continue
        block = "\n".join(
            "  " + line for line in PWA_HEAD.format(rel=prefix).splitlines()
        )
        page.write_text(
            html.replace("</head>", block + "\n  </head>", 1), encoding="utf-8"
        )
    return len(pages)


def _engine_python() -> str:
    """Pick the interpreter that has Zensical: this one, or web/.venv."""
    if importlib.util.find_spec("zensical") is not None:
        return sys.executable
    venv = WEB / ".venv" / "bin" / "python"
    if venv.exists():
        return str(venv)
    sys.exit("zensical is missing: run `make site` (it creates web/.venv)")


def main(argv: list[str]) -> int:
    if "--stats" in argv:
        stats()
        return 0
    python = _engine_python()
    serve = "--serve" in argv
    strict = bool({"--strict", "-s"} & set(argv))
    rest = [arg for arg in argv if arg not in FLAGS]

    stage()
    report = generate.generate(DOCS)
    config = write_config()
    print(f"generated {report['notes']} note cards across {report['areas']} areas")

    command = [
        python,
        "-m",
        "zensical",
        "serve" if serve else "build",
        "-f",
        str(config),
    ]
    if strict and not serve:
        command.append("--strict")
    code = subprocess.call(command + rest, cwd=ROOT)
    if code == 0 and not serve:
        print(f"injected PWA tags into {inject_pwa()} pages")
    return code


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
